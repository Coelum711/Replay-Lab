// Builds src/lipsync/data/zh-vowels.ts from a pinyin dump produced by
// dump-pinyin.swift. Each CJK ideograph U+4E00–U+9FFF becomes one letter:
//   onset (B = b/p/m lips closed, F = f lip-teeth, - = none) is stored in a second
//   string; the vowel letter is A/I/U/E/O, S (ə-like e/en/eng/er), X (n/m/ng
//   syllable: lips stay idle) or ? (no reading).
// Usage: node scripts/lipsync/build-zh-vowel-table.mjs /tmp/pinyin.txt
import fs from 'node:fs';
import { pinyinToMouth } from '../../dist/lipsync/syllables.js';
const rows = fs.readFileSync(process.argv[2], 'utf8').split('\n').slice(0, 0x9FFF - 0x4E00 + 1);
let vowels = '', onsets = '';
for (const row of rows) {
  const m = pinyinToMouth(row.trim().toLowerCase());
  vowels += m ? m.vowel : '?';
  onsets += m?.onset ?? '-';
}
const out = `// Generated by scripts/lipsync/build-zh-vowel-table.mjs — do not edit.
// Source: ICU Han-Latin (Mandarin) transform, derived from Unicode Unihan data
// (Unicode License v3). One letter per code point from U+4E00.
export const ZH_TABLE_START = 0x4E00;
export const ZH_VOWELS = ${JSON.stringify(vowels)};
export const ZH_ONSETS = ${JSON.stringify(onsets)};
`;
fs.writeFileSync(new URL('../../src/lipsync/data/zh-vowels.ts', import.meta.url), out);
console.log('zh-vowels.ts', vowels.length, 'chars,', out.length, 'bytes');

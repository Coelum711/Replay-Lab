import { stripTextTags } from '../core/text-tags.js';
import type { ReplayProject } from '../core/types.js';

function escapeText(text: string): string {
  return text.replace(/\[/g, '［').replace(/\]/g, '］').replace(/\n/g, '[r]');
}

export function exportTyranoScript(project: ReplayProject): string {
  const names = new Map(project.characters.map(c => [c.id, c.name]));
  const out: string[] = ['; Generated by Replay Lab', '[cm]'];
  let currentBg: string | null | undefined;
  let currentBgm: string | null | undefined;
  for (const line of project.lines) {
    if (line.chapterTitle) out.push('', `; # ${line.chapterTitle}`);
    if (line.sceneTitle) out.push('', `; ## ${line.sceneTitle}`);
    if (line.scene && Object.prototype.hasOwnProperty.call(line.scene, 'background') && line.scene.background !== currentBg) {
      currentBg = line.scene.background;
      out.push(currentBg ? `[bg storage="${currentBg}" time=500]` : '[freeimage layer=base]');
    }
    if (line.scene && Object.prototype.hasOwnProperty.call(line.scene, 'bgm') && line.scene.bgm !== currentBgm) {
      currentBgm = line.scene.bgm;
      out.push(currentBgm ? `[playbgm storage="${currentBgm}"]` : '[stopbgm]');
    }
    if (line.type === 'command' && line.command) {
      const command = line.command;
      const target = command.characterId ? (names.get(command.characterId) ?? command.target ?? command.characterId) : command.target;
      if (command.kind === 'bgm') out.push(command.assetId ? `[playbgm storage="${command.assetId}"]` : '[stopbgm]');
      else if (command.kind === 'sfx' && command.assetId) out.push(`[playse storage="${command.assetId}"]`);
      else if (command.kind === 'background') out.push(command.assetId ? `[bg storage="${command.assetId}" time=500]` : '[freeimage layer=base]');
      else if (command.kind === 'wait') out.push(`[wait time=${Math.round(Math.max(0, command.duration ?? 0) * 1000)}]`);
      else if (command.kind === 'dismiss' && target) out.push(`[chara_hide name="${target}"]`);
      else out.push(`; ReplayLab ${line.text}`);
      continue;
    }
    const name = names.get(line.speakerId) ?? 'Unknown';
    if (line.type === 'narration' || line.type === 'system') out.push(`${escapeText(stripTextTags(line.text))}[p]`);
    else out.push(`[chara_name name="${name}"]`, `${escapeText(stripTextTags(line.text))}[p]`);
  }
  return out.join('\n') + '\n';
}

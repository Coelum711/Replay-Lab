import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';

test('Studio starts, imports dialogue and keeps project settings wired after desktop layout mounts',async t=>{
  const dom=new JSDOM(await readFile(new URL('../web/studio.html',import.meta.url),'utf8'),{url:'http://localhost/web/studio.html'}),w=dom.window;
  const context=new Proxy({measureText:text=>({width:String(text).length*8}),createLinearGradient:()=>({addColorStop(){}}),createRadialGradient:()=>({addColorStop(){}})}, {get:(target,key)=>key in target?target[key]:()=>{}});
  w.HTMLCanvasElement.prototype.getContext=function(){return context;};
  w.HTMLElement.prototype.scrollIntoView=function(){};
  w.HTMLElement.prototype.scrollTo=function(){};
  const globals={window:w,document:w.document,location:w.location,localStorage:w.localStorage,CustomEvent:w.CustomEvent,Event:w.Event,HTMLElement:w.HTMLElement,HTMLInputElement:w.HTMLInputElement,HTMLTextAreaElement:w.HTMLTextAreaElement,HTMLSelectElement:w.HTMLSelectElement,Image:w.Image,requestAnimationFrame:()=>0,cancelAnimationFrame(){},ResizeObserver:class{observe(){}disconnect(){}},IntersectionObserver:class{observe(){}disconnect(){}},getComputedStyle:w.getComputedStyle.bind(w),matchMedia:()=>({matches:false,addEventListener(){}})};
  const previous=new Map(Object.keys(globals).map(k=>[k,globalThis[k]]));Object.assign(globalThis,globals);
  w.matchMedia=globals.matchMedia;w.requestAnimationFrame=globals.requestAnimationFrame;w.confirm=()=>true;
  t.after(async()=>{await new Promise(r=>setTimeout(r,700));for(const [key,value] of previous)globalThis[key]=value;w.close();});
  await import('../web/studio.js');await import('../web/desktop-ui.js');await new Promise(r=>setTimeout(r,0));
  const $=id=>w.document.getElementById(id);
  $('homeScript').click();$('logInput').value='Arthur: Hello.\nFrancis: Good evening.';$('parseText').click();
  await new Promise(r=>setTimeout(r,50));
  assert.equal($('stageReady').hidden,false);assert.match($('summary').textContent,/2/);
  const input=$('projectSpeechLanguage');input.value='fr';input.dispatchEvent(new w.Event('change'));
  assert.equal(input.closest('dialog').id,'appSettingsDialog');assert.equal(input.value,'fr');
  assert.equal($('studioHome').hidden,true);
  assert.equal($('maxOnStageEdit').closest('#workbenchPerformance')?.id,'workbenchPerformance');
  assert.equal($('stageModeEdit').closest('#workbenchPerformance')?.id,'workbenchPerformance');
  assert.equal($('stageDetails').closest('#workbenchPerformance')?.id,'workbenchPerformance');
  assert.equal(w.document.querySelectorAll('#maxOnStageEdit').length,1);
  $('maxOnStageEdit').value='1';$('maxOnStageEdit').dispatchEvent(new w.Event('change'));
  assert.match($('stageQuickRoster').textContent,/当前 1 人/);
  $('stageQuickChoose').click();assert.equal($('stageModeEdit').value,'custom');assert.equal($('customStageWrap').hidden,false);assert.equal($('stageDetails').open,true);
  assert.match($('stageQuickRoster').textContent,/当前 1 人/,'choosing a custom roster retains the currently visible actor');
  w.document.querySelector('[data-workbench-size="expanded"]').click();assert.equal($('workbench').dataset.size,'expanded');
  $('workbenchResize').dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowUp',bubbles:true}));assert.equal($('workbench').dataset.size,'custom');
  $('stageProjectionMode').value='2.5d';$('stageProjectionMode').dispatchEvent(new w.Event('change'));
  w.document.querySelector('[data-stage-view="top"]').click();assert.equal($('stageSpatialViewport').hidden,false);
  w.document.querySelector('[data-view-apply]').click();assert.equal($('stageSpatialViewport').hidden,true);
  assert.equal(w.document.querySelector('[data-camera-value="pitch"]').value,'90');
  $('cameraEditToggle').click();assert.equal($('cameraControls').open,true);

  const q=selector=>w.document.querySelector(selector);
  q('[data-view="characters"]').click();
  const theme=w.document.createElement('style');theme.textContent=await readFile(new URL('../web/studio-theme.css',import.meta.url),'utf8');w.document.head.append(theme);
  const findChip=name=>[...w.document.querySelectorAll('.character-chip')].find(button=>button.title===name);
  const longName='Francis Very Long Character Name';findChip('Francis').click();
  q('.character-detail [data-name]').value=longName;q('.character-detail [data-name]').dispatchEvent(new w.Event('change'));
  const search=q('[data-character-search]');search.value='Francis';search.dispatchEvent(new w.Event('input'));
  findChip(longName).click();assert.equal(q('[data-character-search]').value,'Francis');assert.equal(findChip('Arthur').hidden,true);
  assert.equal(w.getComputedStyle(findChip('Arthur')).display,'none');
  assert.equal(w.getComputedStyle(findChip(longName)).minHeight,'44px');
  assert.equal(w.getComputedStyle(findChip(longName)).whiteSpace,'normal');
  assert.match(w.getComputedStyle(q('.character-picker')).gridTemplateColumns,/152px/);
  assert.equal(q('.character-chip.active .character-chip-name').textContent,longName);
  q('[data-character-open-delete]').click();assert.equal(q('[data-character-delete-review]').hidden,false);
  assert.equal(q('[data-character-delete-apply]').disabled,true,'used roles must retain their authored lines through merge');
  q('[data-character-delete-merge]').click();assert.equal(q('.character-identity').open,true);
  assert.equal(q('[data-character-merge-source]').value,findChip(longName).dataset.characterId);
  assert.equal(q('.character-identity').classList.contains('advanced-only'),false);
  q('[data-character-merge-apply]').click();assert.equal(findChip(longName),undefined);
  assert.ok(findChip('Arthur'));assert.match($('importStatus').textContent,/1 句台词/);
  $('undoEdit').click();await new Promise(r=>setTimeout(r,20));assert.ok(findChip(longName));
  q('[data-add-character]').click();assert.equal(q('[data-character-search]').value,'');
  assert.ok(findChip('角色1'));q('[data-character-open-delete]').click();
  assert.equal(q('[data-character-delete-apply]').disabled,false);q('[data-character-delete-apply]').click();
  assert.equal(findChip('角色1'),undefined);$('undoEdit').click();await new Promise(r=>setTimeout(r,20));assert.ok(findChip('角色1'));

});
